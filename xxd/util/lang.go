func I18n(lang string) {
	initLangMap()

	if lang == "zh" {
		GetLang = func(keys ...string) string {
			result := ""
			for i := range keys {
				key := keys[i]
				str := langMap[key]
				if str == "" {
					str = key
				}
				result += str
			}
			return result
		}
	} else {
		GetLang = func(keys ...string) string {
			result := ""
			for i := range keys {
				key := keys[i]
				result += key
			}
			return result
		}
	}
}
